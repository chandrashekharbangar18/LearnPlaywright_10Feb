// Functions --> It is a block of code that performs a specific task.
// It can take inputs, process them, and return an output. 
// Functions help in organizing code, making it reusable, and improving readability.

// Ex1
 function getResult(score){
    return score >= 50 ? "Pass" : "Fail";
 }
 getResult(75); // Output: "Pass"
 getResult(45); // Output: "Fail"
 getResult(50); // Output: "Pass"